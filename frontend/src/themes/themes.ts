// Canonical list of CSS variable keys; drives both the TypeScript interface and runtime iteration.
// Adding a key here updates ThemeVariables and CSS_VAR_KEYS.
export const THEME_VAR_KEYS = [
  'background',
  'foreground',
  'card',
  'card-foreground',
  'primary',
  'primary-foreground',
  // Badge text on a tint of this theme's own primary hue.
  'primary-on-tint',
  'secondary',
  'secondary-foreground',
  'muted',
  'muted-foreground',
  'accent',
  'accent-foreground',
  'destructive',
  'destructive-foreground',
  // Badge text on a tint of this theme's own destructive hue.
  'destructive-on-tint',
  // success/warning start as the old hardcoded Tailwind green/amber pairs in
  // every theme; per-theme tuning can come later.
  'success',
  'success-foreground',
  'success-on-tint',
  'warning',
  'warning-foreground',
  'warning-on-tint',
  'border',
  'input',
  'ring',
] as const;

type ThemeVarKey = (typeof THEME_VAR_KEYS)[number];
export type ThemeVariables = Record<ThemeVarKey, string>;

type ThemeGroup = 'Default' | 'Catppuccin' | 'Dracula' | 'Nord' | 'Gruvbox' | 'Solarized' | 'Rose Pine' | 'Kanagawa' | 'Ayu' | 'Other';

interface ThemePair {
  id: string;
  label: string;
  group: ThemeGroup;
  light: ThemeVariables | null;
  dark: ThemeVariables | null;
  accentColor: string;
}

